"""Generate collision-free waypoints from the targets and obstacles
defined in config/mission.yaml.

Usage (from the project root):
    python3 scripts/plan_route.py
    python3 scripts/plan_route.py --config other.yaml --output out.yaml

The result is a complete mission file (connection, mission, safety) with the
`mission.waypoints` list filled in, in the format waypoint_mission.py reads.
"""

import argparse
import sys
from pathlib import Path

import yaml

from path_planning import (
    Obstacle,
    PathPlanner,
    PlannerConfig,
    Point2D,
)

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CONFIG = PROJECT_ROOT / "config" / "mission.yaml"
DEFAULT_OUTPUT = PROJECT_ROOT / "config" / "planned_mission.yaml"

# Sections used only by the planner; not copied to the output file.
PLANNER_ONLY_KEYS = ("planner", "obstacles", "targets")

START = Point2D(0.0, 0.0)  # waypoints are offsets from the drone's start


class ConfigError(Exception):
    pass


def number(entry, key, where):
    if not isinstance(entry, dict) or key not in entry:
        raise ConfigError(f"{where} must define '{key}'.")
    try:
        return float(entry[key])
    except (TypeError, ValueError):
        raise ConfigError(f"{where}: '{key}' must be a number.") from None


def load_point(entry, where):
    return Point2D(
        number(entry, "north_m", where),
        number(entry, "east_m", where),
    )


def load_yaml(path):
    try:
        with path.open("r", encoding="utf-8") as file:
            config = yaml.safe_load(file)
    except FileNotFoundError:
        raise ConfigError(f"Config file not found: {path}") from None
    except yaml.YAMLError as error:
        raise ConfigError(f"Invalid YAML in {path}: {error}") from None

    if not isinstance(config, dict):
        raise ConfigError("Mission configuration must be a YAML mapping.")
    return config


def build_planner(config):
    settings = config.get("planner") or {}
    defaults = PlannerConfig()

    try:
        planner_config = PlannerConfig(
            min_north_m=float(settings.get("min_north_m", defaults.min_north_m)),
            max_north_m=float(settings.get("max_north_m", defaults.max_north_m)),
            min_east_m=float(settings.get("min_east_m", defaults.min_east_m)),
            max_east_m=float(settings.get("max_east_m", defaults.max_east_m)),
            resolution_m=float(settings.get("resolution_m", defaults.resolution_m)),
            safety_margin_m=float(
                settings.get("safety_margin_m", defaults.safety_margin_m)
            ),
        )
    except (TypeError, ValueError) as error:
        raise ConfigError(f"Invalid 'planner' section: {error}") from None

    planner = PathPlanner(planner_config)

    for index, entry in enumerate(config.get("obstacles") or [], start=1):
        where = f"Obstacle {index}"
        center = load_point(entry, where)
        radius = number(entry, "radius_m", where)
        try:
            planner.add_obstacle(Obstacle(center, radius))
        except ValueError as error:
            raise ConfigError(f"{where}: {error}") from None

    return planner


def plan_route(planner, targets):
    route = []
    current = START

    for index, target in enumerate(targets, start=1):
        if not planner.is_point_free(target):
            raise ConfigError(
                f"Target {index} ({target.north_m}, {target.east_m}) is "
                "outside the flight area or too close to an obstacle."
            )

        leg = planner.plan(current, target)
        if leg is None:
            raise ConfigError(
                f"No safe path to target {index} "
                f"({target.north_m}, {target.east_m}) from "
                f"({current.north_m}, {current.east_m})."
            )

        route.extend(leg)
        current = target

    return route


def write_mission(config, route, output_path):
    mission_file = {
        key: value for key, value in config.items() if key not in PLANNER_ONLY_KEYS
    }
    mission = dict(mission_file.get("mission") or {})
    mission["waypoints"] = [
        {"north_m": round(p.north_m, 2), "east_m": round(p.east_m, 2)}
        for p in route
    ]
    mission_file["mission"] = mission

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as file:
        file.write(
            "# GENERATED by scripts/plan_route.py - do not edit by hand.\n"
            "# Change targets/obstacles in config/mission.yaml and re-run.\n\n"
        )
        yaml.safe_dump(mission_file, file, sort_keys=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    if args.output.resolve() == args.config.resolve():
        sys.exit(
            "ERROR: --output must differ from --config, otherwise the "
            "targets and obstacles would be overwritten."
        )

    try:
        config = load_yaml(args.config)

        raw_targets = config.get("targets")
        if not raw_targets:
            raise ConfigError("Config must contain at least one target.")
        targets = [
            load_point(entry, f"Target {i}")
            for i, entry in enumerate(raw_targets, start=1)
        ]

        planner = build_planner(config)
        route = plan_route(planner, targets)
        write_mission(config, route, args.output)

    except ConfigError as error:
        sys.exit(f"ERROR: {error}")

    print(f"Planned {len(route)} waypoints for {len(targets)} targets:")
    for index, point in enumerate(route, start=1):
        print(f"  WP{index}: north={point.north_m:.1f} m, east={point.east_m:.1f} m")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
